// Runs before bundling (after the release build). Writes an NSIS hook that
// installs, beside Quill.exe:
// - the sherpa-onnx runtime DLLs, which cargo placed next to the release exe;
// - the Visual C++ runtime DLLs Quill needs (app-local deployment, which
//   Microsoft allows), so a fresh Windows install needs no separate
//   redistributable and no admin prompt.
// Uninstall removes them again.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const SHERPA = ["onnxruntime.dll", "onnxruntime_providers_shared.dll", "sherpa-onnx-c-api.dll", "sherpa-onnx-cxx-api.dll"];
// Quill.exe imports MSVCP140, which loads the two VCRUNTIME DLLs.
const VC_RUNTIME = ["msvcp140.dll", "vcruntime140.dll", "vcruntime140_1.dll"];

function fail(message) {
  console.error(message);
  process.exit(1);
}

/** The newest x64 CRT folder under Visual Studio's redistributables. */
function vcRuntimeDir() {
  const vswhere = "C:\\Program Files (x86)\\Microsoft Visual Studio\\Installer\\vswhere.exe";
  if (!existsSync(vswhere)) fail("vswhere.exe not found: install Visual Studio Build Tools");
  const vs = execFileSync(vswhere, ["-latest", "-products", "*", "-property", "installationPath"], { encoding: "utf8" }).trim();
  const redist = join(vs, "VC", "Redist", "MSVC");
  const versions = readdirSync(redist).filter((v) => /^\d/.test(v)).sort().reverse();
  for (const v of versions) {
    const x64 = join(redist, v, "x64");
    if (!existsSync(x64)) continue;
    const crt = readdirSync(x64).find((d) => /^Microsoft\.VC\d+\.CRT$/.test(d));
    if (crt) return join(x64, crt);
  }
  fail(`no Visual C++ runtime found under ${redist}`);
}

const target = resolve(process.env.CARGO_TARGET_DIR ?? "target", "release");
const vc = vcRuntimeDir();
const files = [...SHERPA.map((d) => join(target, d)), ...VC_RUNTIME.map((d) => join(vc, d))];
for (const f of files) {
  if (!existsSync(f)) fail(`missing ${f}: build the release binary first`);
}

const bs = "\\";
const names = [...SHERPA, ...VC_RUNTIME];
const nsh = [
  "; Generated by scripts/stage-dlls.mjs. Do not edit.",
  "!macro NSIS_HOOK_POSTINSTALL",
  '  SetOutPath "$INSTDIR"',
  ...files.map((f) => `  File "${f}"`),
  "!macroend",
  "",
  "!macro NSIS_HOOK_POSTUNINSTALL",
  ...names.map((d) => `  Delete "$INSTDIR${bs}${d}"`),
  '  ; "Delete app data" also removes Quill\'s models (several GB) and settings.',
  "  ${If} $DeleteAppDataCheckboxState = 1",
  `    RmDir /r "$LOCALAPPDATA${bs}Quill${bs}Models"`,
  `    RmDir /r "$LOCALAPPDATA${bs}Quill${bs}Eval"`,
  `    RmDir /r "$APPDATA${bs}Quill"`,
  '    RMDir "$INSTDIR"',
  "  ${EndIf}",
  "!macroend",
  "",
].join("\n");
mkdirSync(resolve("src-tauri", "windows"), { recursive: true });
writeFileSync(resolve("src-tauri", "windows", "hooks.nsh"), nsh);
console.log(`NSIS hook installs ${SHERPA.length} sherpa DLLs from ${target} and ${VC_RUNTIME.length} VC++ runtime DLLs from ${vc}`);
