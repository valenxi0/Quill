// Runs before bundling (after the release build). Writes an NSIS hook that
// installs the sherpa-onnx runtime DLLs, which cargo placed next to the
// release exe, beside Quill.exe, and removes them on uninstall.
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const DLLS = ["onnxruntime.dll", "onnxruntime_providers_shared.dll", "sherpa-onnx-c-api.dll", "sherpa-onnx-cxx-api.dll"];
const target = resolve(process.env.CARGO_TARGET_DIR ?? "target", "release");
for (const dll of DLLS) {
  if (!existsSync(join(target, dll))) {
    console.error(`missing ${join(target, dll)}: build the release binary first`);
    process.exit(1);
  }
}
const bs = "\\";
const install = DLLS.map((d) => `  File "${join(target, d)}"`).join("\n");
const remove = DLLS.map((d) => `  Delete "$INSTDIR${bs}${d}"`).join("\n");
const nsh = [
  "; Generated by scripts/stage-dlls.mjs. Do not edit.",
  "!macro NSIS_HOOK_POSTINSTALL",
  '  SetOutPath "$INSTDIR"',
  install,
  "!macroend",
  "",
  "!macro NSIS_HOOK_POSTUNINSTALL",
  remove,
  '  ; "Delete app data" also removes Quill\'s models (several GB) and settings.',
  "  ${If} $DeleteAppDataCheckboxState = 1",
  `    RmDir /r "$LOCALAPPDATA${bs}Quill${bs}Models"`,
  `    RmDir /r "$LOCALAPPDATA${bs}Quill${bs}Eval"`,
  `    RmDir /r "$APPDATA${bs}Quill"`,
  '    RMDir "$INSTDIR"',
  "  ${EndIf}",
  "!macroend",
  "",
].join("\n");
mkdirSync(resolve("src-tauri", "windows"), { recursive: true });
writeFileSync(resolve("src-tauri", "windows", "hooks.nsh"), nsh);
console.log(`NSIS hook installs ${DLLS.length} DLLs from ${target}`);
